export function getPortalPage<K extends PortalPageKey>(
  key: K,
  locale: Locale
): (typeof portalPages)[K]["sv"] | (typeof portalPages)[K]["en"] {
  return locale === "en" ? portalPages[key].en : portalPages[key].sv;
}

